            const k = keszlet(cel);
            const erdo = cel.map(t => faEpit(t.i, t.q, [], k));
            return `<div class="treebar">
                <button data-tb="open">Mind kinyit</button>
                <button data-tb="close">Mind bezár</button></div>
              <ul class="tree">${erdo.map(n => faHTML(n, true)).join("")}</ul>`;
