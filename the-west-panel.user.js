    /* Korlátozott gyűjtés — kizárólag a saját ablak részfájában. */
    function skinGyujtes(fo) {
        const ki = { insetek: [], quadok: {} };
        Object.keys(SKIN_QUAD).forEach(k => ki.quadok[k] = []);
        let db = 0;
        const verem = [{ el: fo, m: 0 }];
        while (verem.length && db < SKIN_MAXELEM) {
            const t = verem.pop();
            db++;
            let cl = null;
            try { cl = t.el.classList; } catch (e) { cl = null; }
            if (cl) {
                if (cl.contains(SKIN_INSET)) ki.insetek.push(t.el);
                if (cl.contains(SKIN_KERET)) {
                    Object.keys(SKIN_QUAD).forEach(k => { if (cl.contains(k)) ki.quadok[k].push(t.el); });
                }
            }
            if (t.m >= SKIN_MELYSEG) continue;
            let gy = [];
            try { gy = t.el.children ? Array.prototype.slice.call(t.el.children) : []; } catch (e) { gy = []; }
            for (let i = gy.length - 1; i >= 0; i--) verem.push({ el: gy[i], m: t.m + 1 });
        }
        return ki;
    }

